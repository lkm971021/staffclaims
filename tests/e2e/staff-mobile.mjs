// Quick scripted walk-through of the staff flow on an emulated iPhone (headless Chromium).
import { createRequire } from "module";
const { chromium, devices } = createRequire(import.meta.url)(process.env.PW_PATH || "playwright");
const BASE = process.env.BASE_URL || "http://localhost:3000";
const OUT = process.env.SHOTS || "/tmp";
const device = devices[process.env.DEVICE || "iPhone 13"];
const browser = await chromium.launch();
const ctx = await browser.newContext({ ...device });
const page = await ctx.newPage();
const errors = [];
page.on("pageerror", (e) => errors.push(e.message));
page.on("console", (m) => m.type() === "error" && errors.push(m.text()));
const shot = (n) => page.screenshot({ path: `${OUT}/${n}.png`, fullPage: true });

await page.goto(`${BASE}/login`);
await page.fill("#email", process.env.EMAIL || "alice@example.test");
await page.fill("#password", "Demo-Claims-2026!");
await page.click("button:has-text('Sign in')");
await page.waitForURL(/\/staff/);
await shot("01-dashboard");
await page.click("text=NEW EXPENSE CLAIM");
await page.click("text=Start claim");
await page.waitForURL(/\/staff\/claims\/c/);
await page.click("text=Add expense");
// gallery upload -> page editor
const [chooser] = await Promise.all([page.waitForEvent("filechooser"), page.click("button:has-text('Gallery')")]);
await chooser.setFiles("tests/fixtures/receipt-c.jpg");
await page.waitForSelector("text=Adjust receipt");
await shot("02-editor");
await page.click("button:has-text('Use page')");
await page.waitForSelector("img[alt='enhanced-receipt-c.jpg'], img[alt^='receipt-c']", { timeout: 20000 }).catch(() => {});
await page.waitForTimeout(1500);
await page.fill("#amount", "120.00");
await page.selectOption("#category", { label: "UPKEEP OF SHOP EQUIPMENT" });
await page.fill("#supplier", "Demo Hardware Trading");
await page.fill("#description", "Replacement light bulbs");
await page.fill("#purpose", "Treatment room lighting repair");
await page.fill("#receiptNo", "HW-7781");
await page.fill("#expenseDate", "2026-10-20");
await shot("03-expense-form");
await page.click("button:has-text('Save expense')");
await page.waitForSelector("text=Demo Hardware Trading");
await shot("04-claim-draft");
await page.click("button:has-text('Submit to Finance')");
await page.click("button:has-text('Confirm & submit')");
await page.waitForSelector("text=Submitted", { timeout: 20000 });
await page.waitForTimeout(1000);
await page.reload();
await shot("05-submitted");
console.log(JSON.stringify({ url: page.url(), errors }, null, 1));
await browser.close();
